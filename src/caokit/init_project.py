"""`caokit init <repo>`: scaffold .company/, write ROSTER.md and merge .gitignore."""

from collections.abc import Iterator
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path
from typing import TYPE_CHECKING

from .adapters import ROLES, Runner, default_runner, load_adapter
from .config import Config
from .gitignore import BEGIN, merge_gitignore
from .render import profile_name
from .stack import Suggestion, suggest_validation

if TYPE_CHECKING:  # typing-only: importlib.abc.Traversable is not importable at runtime on 3.14+
    from importlib.abc import Traversable

# Directories agents write into. Created even though git does not track empty
# directories, because the whole of .company/ except contracts/ is ignored anyway.
EMPTY_DIRS = ["artifacts", "decisions", "handoffs", "research", "reviews", "tasks"]


class InitError(Exception):
    """Raised when a project cannot be initialised (not a git repo, bad path)."""


@dataclass
class InitResult:
    """What ``init_project`` did, for the CLI to report."""

    created: list[str] = field(default_factory=list)  # scaffold files newly written
    kept: list[str] = field(default_factory=list)  # existing files left untouched
    warnings: list[str] = field(default_factory=list)
    suggestion: Suggestion | None = None  # detected validation command, if any


def render_roster_md(cfg: Config, suggestion: Suggestion | None) -> str:
    """Render ``.company/ROSTER.md``, the file the General reads to dispatch.

    Args:
        cfg: The company configuration; one table row per role.
        suggestion: Detected validation command, or None when nothing was detected.

    Returns:
        The Markdown text, ending in a newline.
    """
    rows = []
    for role in ROLES:
        b = cfg.roles[role]
        a = load_adapter(b.tool)
        model = b.model or "(tool default)"
        rows.append(
            f"| {role} | `{profile_name(role, b.tool)}` | {b.tool} | {model} | {a.enforcement} |"
        )
    lines = [
        "# Roster",
        "",
        "Generated by `caokit init` from `caokit.toml`. Regenerate; do not hand-edit.",
        "",
        "Dispatch **only** to the profiles listed here, using the name verbatim. "
        "Never guess a profile name.",
        "",
        "| Role | CAO profile | Tool | Model | Enforcement |",
        "|---|---|---|---|---|",
        *rows,
        "",
        "`soft` enforcement means the tool's limits are advisory only.",
        "",
        "## Suggested validation command (unconfirmed)",
        "",
    ]
    if suggestion is None:
        lines.append(
            "None detected. The human must supply the authorised validation command "
            "at task approval."
        )
    else:
        if suggestion.command:  # CI-only hints carry a reason but no command
            lines += [f"`{suggestion.command}`", ""]
        lines.append(f"Detected because: {suggestion.reason}.")
        if suggestion.note:
            lines += ["", f"Note: {suggestion.note}"]
        lines += [
            "",
            "The human must confirm this at task approval; "
            "never treat it as authorised until then.",
        ]
    return "\n".join(lines) + "\n"


def _walk(node: "Traversable", rel: str = "") -> Iterator[tuple[str, "Traversable"]]:
    """Yield ``(relative/posix/path, file)`` for every file under ``node``, sorted."""
    for child in sorted(node.iterdir(), key=lambda p: p.name):
        r = rel + child.name
        if child.is_dir():
            yield from _walk(child, r + "/")
        else:
            yield r, child


def _ignores_whole_company(text: str) -> bool:
    """Return True if the user's own rules ignore all of ``.company/``.

    Only text before our managed block counts; our block deliberately ignores
    ``.company/*`` while re-including ``contracts/``.
    """
    before = text.split(BEGIN)[0]
    return any(
        line.strip() in (".company", ".company/", "/.company", "/.company/")
        for line in before.splitlines()
    )


def init_project(repo: Path, cfg: Config, runner: Runner = default_runner) -> InitResult:
    """Scaffold ``.company/`` in a git repo, write ROSTER.md and merge .gitignore.

    Existing scaffold files are never overwritten, so re-running is safe.
    ROSTER.md is the exception: it is generated output and is rewritten.

    Args:
        repo: Root of the target git repository.
        cfg: The company configuration used to render ROSTER.md.
        runner: Command runner used by stack detection (injectable for tests).

    Returns:
        A summary of created and kept files, warnings and the detected
        validation command.

    Raises:
        InitError: ``repo`` is not a directory or has no ``.git``.
    """
    repo = Path(repo).resolve()
    if not repo.is_dir():
        raise InitError(f"not a directory: {repo}")
    # `.git` may be a file (worktrees, submodules), so test existence, not is_dir.
    if not (repo / ".git").exists():
        raise InitError(f"{repo} is not a git repository root (no .git); run `git init` first")
    res = InitResult()
    company = repo / ".company"
    root = resources.files("caokit") / "data" / "scaffold" / "company"
    for rel, src in _walk(root):
        dest = company / rel
        if dest.exists():
            res.kept.append(".company/" + rel)  # never clobber the project's own edits
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(src.read_bytes())
        res.created.append(".company/" + rel)
    for d in EMPTY_DIRS:
        (company / d).mkdir(parents=True, exist_ok=True)
    res.suggestion = suggest_validation(repo, runner=runner)
    (company / "ROSTER.md").write_text(render_roster_md(cfg, res.suggestion), encoding="utf-8")
    gi = repo / ".gitignore"
    existing = gi.read_text(encoding="utf-8") if gi.exists() else ""
    if _ignores_whole_company(existing):
        res.warnings.append(
            ".gitignore already ignores all of .company/; git cannot re-include "
            ".company/contracts/ under an ignored parent. Remove that line so "
            "contracts are tracked."
        )
    gi.write_text(merge_gitignore(existing), encoding="utf-8")
    return res
